use crate::core::errors::BitOSDTResult;
use std::fs;
use std::path::{Path, PathBuf};
use tracing::info;

/// Startnet.cmd generator for WinPE boot
pub struct StartnetGenerator;

/// Startnet configuration
pub struct StartnetConfig {
    /// Initialize network
    pub initialize_network: bool,
    /// Network initialization timeout seconds
    pub network_timeout: u32,
    /// PowerShell scripts to run
    pub powershell_scripts: Vec<String>,
    /// Launch custom application
    pub launch_app: Option<String>,
    /// Launch parameters
    pub launch_params: Option<String>,
    /// Show debug console
    pub show_console: bool,
    /// Log file path
    pub log_path: Option<String>,
}

impl Default for StartnetConfig {
    fn default() -> Self {
        Self {
            initialize_network: true,
            network_timeout: 30,
            powershell_scripts: Vec::new(),
            launch_app: None,
            launch_params: None,
            show_console: false,
            log_path: Some("X:\\BitOSDT\\Logs\\startnet.log".to_string()),
        }
    }
}

impl StartnetGenerator {
    /// Generate startnet.cmd content
    pub fn generate(config: &StartnetConfig) -> String {
        let mut content = String::new();

        // Header
        content.push_str("@echo off\r\n");
        content.push_str("rem BitOSDT Startnet.cmd\r\n");
        content.push_str("rem Generated by BitOSDT 2.0\r\n");
        content.push_str("rem ===============================\r\n\r\n");

        // Set up logging if enabled
        if let Some(ref log_path) = config.log_path {
            let log_dir = Path::new(log_path).parent().unwrap_or(Path::new("X:\\"));
            content.push_str(&format!(
                "if not exist \"{}\" mkdir \"{}\"\r\n",
                log_dir.display(),
                log_dir.display()
            ));
            content.push_str(&format!(
                "echo %DATE% %TIME% - BitOSDT Startnet starting >> \"{}\"\r\n\r\n",
                log_path
            ));
        }

        // Initialize WinPE basic components
        content.push_str("rem Initialize WinPE\r\n");
        content.push_str("wpeinit\r\n\r\n");

        // Network initialization
        if config.initialize_network {
            content.push_str("rem Initialize network\r\n");
            content.push_str(&format!(
                "echo Waiting for network connection ({}s timeout)...\r\n",
                config.network_timeout
            ));

            if let Some(ref log_path) = config.log_path {
                content.push_str(&format!(
                    "echo %DATE% %TIME% - Starting network initialization >> \"{}\"\r\n",
                    log_path
                ));
            }

            // Wait for network adapter
            content.push_str(&format!(
                "powershell.exe -NoProfile -ExecutionPolicy Bypass -Command \"$timeout={}; $timer=0; while (!(Test-Connection -ComputerName 1.1.1.1 -Count 1 -Quiet) -and $timer -lt $timeout) {{ Start-Sleep -Seconds 1; $timer++ }}\"\r\n",
                config.network_timeout
            ));

            if let Some(ref log_path) = config.log_path {
                content.push_str(&format!(
                    "echo %DATE% %TIME% - Network initialization complete >> \"{}\"\r\n\r\n",
                    log_path
                ));
            }
        }

        // Run PowerShell scripts
        for (index, script) in config.powershell_scripts.iter().enumerate() {
            content.push_str(&format!("rem PowerShell Script {}\r\n", index + 1));

            if let Some(ref log_path) = config.log_path {
                content.push_str(&format!(
                    "echo %DATE% %TIME% - Running PowerShell script {} >> \"{}\"\r\n",
                    index + 1,
                    log_path
                ));
            }

            content.push_str(&format!(
                "powershell.exe -NoProfile -ExecutionPolicy Bypass -File \"{}\"\r\n\r\n",
                script
            ));
        }

        // Launch application
        if let Some(ref app) = config.launch_app {
            content.push_str("rem Launch application\r\n");

            if let Some(ref log_path) = config.log_path {
                content.push_str(&format!(
                    "echo %DATE% %TIME% - Launching {} >> \"{}\"\r\n",
                    app, log_path
                ));
            }

            let params = config.launch_params.as_deref().unwrap_or("");
            if config.show_console {
                content.push_str(&format!("start \"\" \"{}\" {}\r\n", app, params));
            } else {
                content.push_str(&format!("start \"\" /MIN \"{}\" {}\r\n", app, params));
            }
        }

        // Final log entry
        if let Some(ref log_path) = config.log_path {
            content.push_str(&format!(
                "\r\necho %DATE% %TIME% - Startnet.cmd complete >> \"{}\"\r\n",
                log_path
            ));
        }

        content
    }

    /// Generate startnet.cmd for OSDCloud deployment
    pub fn generate_osdcloud(use_start_osdcloud: bool) -> String {
        let scripts = if use_start_osdcloud {
            vec!["X:\\BitOSDT\\Start-OSDCloud.ps1".to_string()]
        } else {
            vec!["X:\\BitOSDT\\Start-BitOSDT.ps1".to_string()]
        };

        let config = StartnetConfig {
            initialize_network: true,
            network_timeout: 60,
            powershell_scripts: scripts,
            launch_app: None,
            launch_params: None,
            show_console: false,
            log_path: Some("X:\\BitOSDT\\Logs\\startnet.log".to_string()),
        };

        Self::generate(&config)
    }

    /// Generate startnet.cmd for BitOSDT with GUI
    pub fn generate_bitosdt_gui(bitosdt_exe: &str) -> String {
        let config = StartnetConfig {
            initialize_network: true,
            network_timeout: 60,
            powershell_scripts: Vec::new(),
            launch_app: Some(bitosdt_exe.to_string()),
            launch_params: None,
            show_console: false,
            log_path: Some("X:\\BitOSDT\\Logs\\startnet.log".to_string()),
        };

        Self::generate(&config)
    }

    /// Generate startnet.cmd for network boot (lightweight ISO)
    pub fn generate_network_boot(server_url: &str) -> String {
        let network_script = format!(
            r#"# Download and execute BitOSDT from network
$ProgressPreference = 'SilentlyContinue'
$serverUrl = '{}'
$localPath = 'X:\BitOSDT'

Write-Host 'BitOSDT Network Boot' -ForegroundColor Cyan
Write-Host "Downloading from: $serverUrl"

# Create local directory
New-Item -Path $localPath -ItemType Directory -Force | Out-Null

# Download main executable
try {{
    Invoke-WebRequest -Uri "$serverUrl/bitosdt.exe" -OutFile "$localPath\bitosdt.exe" -UseBasicParsing
    Write-Host 'Download complete' -ForegroundColor Green
    
    # Launch BitOSDT
    Start-Process -FilePath "$localPath\bitosdt.exe" -Wait
}} catch {{
    Write-Error "Failed to download BitOSDT: $_"
    Read-Host 'Press Enter to continue to command prompt'
}}
"#,
            server_url
        );

        // Write the PowerShell script content to be embedded
        let mut content = String::new();
        content.push_str("@echo off\r\n");
        content.push_str("rem BitOSDT Network Boot Startnet\r\n");
        content.push_str("rem Generated by BitOSDT 2.0\r\n\r\n");
        content.push_str("wpeinit\r\n\r\n");
        content.push_str("rem Wait for network\r\n");
        content.push_str("echo Waiting for network connection...\r\n");
        content.push_str("powershell.exe -NoProfile -Command \"$timer=0; while (!(Test-Connection -ComputerName 1.1.1.1 -Count 1 -Quiet) -and $timer -lt 60) { Start-Sleep -Seconds 1; $timer++ }\"\r\n\r\n");
        content.push_str("rem Download and run BitOSDT\r\n");
        content.push_str(&format!(
            "powershell.exe -NoProfile -ExecutionPolicy Bypass -Command \"{}\" \r\n",
            network_script.replace('\n', ";").replace('"', "\\\"")
        ));

        content
    }

    /// Write startnet.cmd to WinPE mount point
    pub fn write_to_winpe(mount_point: &Path, content: &str) -> BitOSDTResult<PathBuf> {
        let startnet_path = mount_point
            .join("Windows")
            .join("System32")
            .join("startnet.cmd");

        // Create directory if needed
        if let Some(parent) = startnet_path.parent() {
            fs::create_dir_all(parent)?;
        }

        fs::write(&startnet_path, content)?;
        info!("Written startnet.cmd to {:?}", startnet_path);

        Ok(startnet_path)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_default() {
        let config = StartnetConfig::default();
        let content = StartnetGenerator::generate(&config);

        assert!(content.contains("wpeinit"));
        assert!(content.contains("Test-Connection"));
    }

    #[test]
    fn test_generate_osdcloud() {
        let content = StartnetGenerator::generate_osdcloud(true);
        assert!(content.contains("Start-OSDCloud.ps1"));
    }

    #[test]
    fn test_generate_network_boot() {
        let content = StartnetGenerator::generate_network_boot("http://deploy.local:8080");
        assert!(content.contains("http://deploy.local:8080"));
        assert!(content.contains("Invoke-WebRequest"));
    }
}
